#!/usr/bin/env python3
"""Bakes a bitmap glyph atlas (RGBA, white + alpha) into a C++ header."""
import sys, argparse

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ttf', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--size', type=int, default=40)
    ap.add_argument('--width', type=int, default=1024)
    args = ap.parse_args()

    from PIL import Image, ImageDraw, ImageFont

    size = args.size
    font = ImageFont.truetype(args.ttf, size)

    chars = [chr(c) for c in range(32, 127)]
    chars += [chr(c) for c in range(0x410, 0x450)]
    chars += [chr(0x401), chr(0x451), chr(0xAB), chr(0xBB), chr(0x2014),
              chr(0x2026), chr(0x2116), chr(0xB7), chr(0x2192), chr(0x2715)]

    atlas = Image.new('RGBA', (args.width, 2048), (255, 255, 255, 0))
    glyphs = []
    x, y, rowh = 1, 1, 0
    maxy = 0

    for ch in chars:
        try:
            bbox = font.getbbox(ch)
        except Exception:
            bbox = (0, 0, 0, 0)
        gw = max(0, bbox[2] - bbox[0])
        gh = max(0, bbox[3] - bbox[1])
        adv = int(round(font.getlength(ch)))
        if adv <= 0:
            adv = size // 3
        if gw > 0 and gh > 0:
            if x + gw + 2 > args.width:
                x = 1
                y += rowh + 2
                rowh = 0
            if y + gh + 2 > atlas.height:
                break
            img = Image.new('RGBA', (gw, gh), (255, 255, 255, 0))
            d = ImageDraw.Draw(img)
            d.text((-bbox[0], -bbox[1]), ch, font=font, fill=(255, 255, 255, 255))
            atlas.paste(img, (x, y))
            glyphs.append((ord(ch), x, y, gw, gh, adv, bbox[0], bbox[1]))
            maxy = max(maxy, y + gh + 2)
            x += gw + 2
            rowh = max(rowh, gh)
        else:
            glyphs.append((ord(ch), 0, 0, 0, 0, adv, 0, 0))

    atlas = atlas.crop((0, 0, args.width, max(1, maxy)))
    px = atlas.tobytes()

    with open(args.out, 'w') as f:
        f.write('// generated by tools/make_font.py — do not edit\n')
        f.write('#include "rc.h"\n\n')
        f.write('const unsigned int rc_atlas_w = %d;\n' % atlas.width)
        f.write('const unsigned int rc_atlas_h = %d;\n' % atlas.height)
        f.write('const int rc_font_size = %d;\n\n' % size)
        f.write('const unsigned char rc_atlas_px[] = {\n')
        for i in range(0, len(px), 32):
            f.write(','.join(str(b) for b in px[i:i + 32]) + ',\n')
        f.write('};\n\n')
        f.write('const RCGlyph rc_glyphs[] = {\n')
        for g in glyphs:
            f.write('{%d,%d,%d,%d,%d,%d,%d,%d},\n' % g)
        f.write('};\n')
        f.write('const unsigned int rc_glyphs_count = %d;\n' % len(glyphs))
    print('font atlas: %dx%d, %d glyphs' % (atlas.width, atlas.height, len(glyphs)))

if __name__ == '__main__':
    main()
